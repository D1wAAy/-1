while True:                                # бесконечный цикл, работает пока не выберут 0
    print("1 - сумма от 1 до N")
    print("2 - количество чётных")
    print("3 - таблица умножения")
    print("4 - доп. задание")
    print("0 - выход")
    a = int(input("Выберите пункт: "))     # пользователь выбирает пункт меню
    if a == 0:                             # выход из программы
        break
    elif a == 1:                           # сумма от 1 до N
        total = 0
        n = int(input("Введите N:"))
        for i in range(1, n + 1):
            total += i
        print(total)
    elif a == 2:                           # количество чётных чисел от 1 до N
        n = int(input("Введите число: "))
        count = 0
        for i in range(1, n + 1):
            if i % 2 == 0:
                count += 1
        print("Количество чётных:", count)
    elif a == 3:                           # таблица умножения для введённого числа
        n = int(input("Введите число: "))
        for i in range(1, 10+1):
            m = n * i
            print(n, "*", i, "=", m)
