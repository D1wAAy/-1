n = int(input("Введите количество чисел: "))   # сколько чисел будем вводить
a = int(input())                               # первое число сразу считаем максимумом
for i in range(n - 1):                         # повторяем ещё n-1 раз
    m = int(input())                           # вводим следующее число
    if m > a:                                  # если оно больше текущего максимума
        a = m                                  # обновляем максимум
print("Максимальное число:", a)                # выводим найденный максимум
