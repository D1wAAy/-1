total = 0                          # переменная для суммы чётных чисел
n = int(input("Введите число:"))   # вводим число N
for i in range(1, n+1):            # перебираем числа от 1 до N включительно
    if i % 2 == 0:                 # проверяем, чётное ли число
        total += i                 # если чётное — добавляем к сумме
print("Сумма всех целых чисел:", total)   # выводим итоговую сумму

