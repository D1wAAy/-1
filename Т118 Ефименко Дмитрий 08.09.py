# Запрашиваем у пользователя температуру и сразу переводим в целое число
n = int(input("Сколько градусов на улице?"))
if n >= 35:
    # Если 35 градусов и выше — жарко
    print("Жарко")
elif n < 10:
    # Если меньше 10 градусов — холодно
    print("холодно")
else:
    # Все остальные случаи (от 10 до 34) — нормальная температура
    print("нормально")

