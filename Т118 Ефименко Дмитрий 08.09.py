# Ввод выбора первого и второго игрока
n = input("выбирает игрок 1 (камень/ножницы/бумага): ")
m = input("выбирает игрок 2 (камень/ножницы/бумага): ")
if (n != "камень" and n != "ножницы" and n != "бумага") or (m != "камень" and m != "ножницы" and m != "бумага"):
    # Если ввод первого ИЛИ второго игрока не совпадает ни с одним из допустимых вариантов
    print("Неверный ввод")
elif n == m:
    # Если оба выбрали одно и то же — ничья
    print("Ничья")
elif n == "камень" and m == "ножницы":
    # Камень тупит ножницы
    print("Выиграл игрок 1")
elif n == "ножницы" and m == "бумага":
    # Ножницы режут бумагу
    print("Выиграл игрок 1")
elif n == "бумага" and m == "камень":
    # Бумага накрывает камень
    print("Выиграл игрок 1")
else:
    # Во всех остальных случаях (обратные комбинации) побеждает игрок 2
    print("Выиграл игрок 2")